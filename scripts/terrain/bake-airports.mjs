#!/usr/bin/env node
// The other airfields of each real-world theater — civilian airports and the military fields the missions don't use —
// from OurAirports (public domain, https://github.com/davidmegginson/ourairports-data): every large or medium airport
// inside the theater with an open paved runway of 1200 m or more, except the ones that are already an airbase in
// src/world/theaters/<id>.ts. Written to src/world/theaters/civil.ts as
//   [ident, name, kind, [[threshold lat, lon, other threshold lat, lon, width m], … longest first]]
// kind: 'hub' (large airport), 'regional' (airline service), 'field' (no airline service), 'military'.
//
// Usage: npm run build && node scripts/terrain/bake-airports.mjs
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

async function csv(name) {
  const file = join('.cache', `ourairports-${name}.csv`);
  if (!existsSync(file)) {
    const r = await fetch(`https://raw.githubusercontent.com/davidmegginson/ourairports-data/main/${name}.csv`);
    if (!r.ok) throw new Error(`${name}: HTTP ${r.status}`);
    mkdirSync('.cache', { recursive: true });
    writeFileSync(file, Buffer.from(await r.arrayBuffer()));
  }
  const rows = [];
  for (const line of readFileSync(file, 'utf8').split('\n').slice(1)) {
    if (!line) continue;
    const f = []; let cur = '', q = false;
    for (const ch of line) {
      if (ch === '"') q = !q;
      else if (ch === ',' && !q) { f.push(cur); cur = ''; }
      else cur += ch;
    }
    f.push(cur);
    rows.push(f);
  }
  return rows;
}
const PAVED = /^(ASP|CON|PEM|BIT|ASPH|ASPHALT|CONCRETE|ASP\/CON|CON\/ASP|TARMAC|PAVED)/i;
const MIL = /\b(air ?base|air force|airbase|RAF|NAS|naval|army|military|fliegerhorst|AFB|base a[ée]rienne|\bBA \d+|vliegbasis|flyvestation|flygflottilj|lotnicza|heeresflugplatz|air station)\b/i;
const dist = (a, b, c, d) => {
  const R = 6371000, r = Math.PI / 180;
  return Math.hypot((d - b) * r * Math.cos((a + c) / 2 * r), (c - a) * r) * R;
};

const airports = await csv('airports');   // id, ident, type, name, lat, lon, elev, continent, country, region, municipality, scheduled_service, …
const byAirport = new Map();
for (const r of await csv('runways')) {
  const [, ref, , , widthFt, surface, , closed, , leLat, leLon, , , , , heLat, heLon] = r;
  if (closed === '1' || !PAVED.test(surface) || !leLat || !heLat) continue;
  const p = [+leLat, +leLon, +heLat, +heLon], len = dist(...p);
  if (len < 1200 || !Number.isFinite(len)) continue;
  if (!byAirport.has(ref)) byAirport.set(ref, []);
  byAirport.get(ref).push({ p, len, width: Math.min(60, Math.max(23, Math.round((+widthFt || 148) * 0.3048))) });
}

const out = {};
for (const theater of ['europe', 'gulf']) {
  const mod = await import(`../../build/src/world/theaters/${theater}.js`);
  const lcc = mod[`${theater}Lcc`];
  const T = mod[theater.toUpperCase()];
  const bases = T.airbases.map((ab) => ({ x: ab.x, z: ab.z }));
  const rows = [];
  for (const a of airports) {
    if (a[2] !== 'large_airport' && a[2] !== 'medium_airport') continue;
    const rws = byAirport.get(a[0]);
    if (!rws) continue;
    const c = lcc.forward(+a[4], +a[5]);
    // clear of the map edge and of the theater's own airbases
    if (Math.abs(c.x) > T.half - 20000 || Math.abs(c.z) > T.half - 20000) continue;
    if (bases.some((b) => Math.hypot(b.x - c.x, b.z - c.z) < 6000)) continue;
    if (rows.some((r) => Math.hypot(r.c.x - c.x, r.c.z - c.z) < 5000)) continue;
    rws.sort((p, q) => q.len - p.len);
    const kind = a[2] === 'large_airport' ? 'hub' : MIL.test(a[3]) ? 'military' : a[11] === 'yes' ? 'regional' : 'field';
    rows.push({ c, row: [a[1], a[3], kind, rws.slice(0, 6).map((r) => [...r.p.map((v) => +v.toFixed(5)), r.width])] });
  }
  out[theater] = rows.map((r) => r.row);
  const n = (k) => rows.filter((r) => r.row[2] === k).length;
  console.log(`${theater}: ${rows.length} fields (${n('hub')} hubs, ${n('regional')} regional, ${n('field')} other, ${n('military')} military)`);
}
const body = Object.entries(out).map(([id, rows]) => `  ${id}: [\n${rows.map((r) => `    ${JSON.stringify(r)},`).join('\n')}\n  ],`).join('\n');
writeFileSync('src/world/theaters/civil.ts', `// Generated by scripts/terrain/bake-airports.mjs from OurAirports (public domain) — do not edit by hand.
// Per theater: the airports and airfields that are not mission airbases, as
// [ident, name, kind, runways as [threshold lat, lon, other threshold lat, lon, width m], longest first].
export type FieldKind = 'hub' | 'regional' | 'field' | 'military';
export type FieldRow = [ident: string, name: string, kind: FieldKind, runways: Array<[number, number, number, number, number]>];
export const CIVIL_FIELDS: Record<string, FieldRow[]> = {
${body}
};
`);
