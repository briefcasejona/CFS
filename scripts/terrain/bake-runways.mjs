#!/usr/bin/env node
// Bake the real runway layout of every theater airbase from OurAirports (public domain,
// https://github.com/davidmegginson/ourairports-data): for each AbRow in src/world/theaters/{europe,gulf}.ts the nearest
// airport within 4 km is matched and its open, paved runways of at least 1200 m are written to
// src/world/theaters/runways.ts as [lat, lon, lat, lon, width m] (the two thresholds), longest first.
//
// Usage: node scripts/terrain/bake-runways.mjs
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

async function csv(name) {
  const file = join('.cache', `ourairports-${name}.csv`);
  if (!existsSync(file)) {
    const r = await fetch(`https://raw.githubusercontent.com/davidmegginson/ourairports-data/main/${name}.csv`);
    if (!r.ok) throw new Error(`${name}: HTTP ${r.status}`);
    mkdirSync('.cache', { recursive: true });
    writeFileSync(file, Buffer.from(await r.arrayBuffer()));
  }
  const rows = [];
  for (const line of readFileSync(file, 'utf8').split('\n').slice(1)) {
    if (!line) continue;
    // simple CSV: fields are quoted when they contain commas
    const f = []; let cur = '', q = false;
    for (const ch of line) {
      if (ch === '"') q = !q;
      else if (ch === ',' && !q) { f.push(cur); cur = ''; }
      else cur += ch;
    }
    f.push(cur);
    rows.push(f);
  }
  return rows;
}

const PAVED = /^(ASP|CON|PEM|BIT|ASPH|ASPHALT|CONCRETE|ASP\/CON|CON\/ASP|TARMAC|PAVED)/i;
const dist = (a, b, c, d) => {
  const R = 6371000, r = Math.PI / 180;
  const x = (d - b) * r * Math.cos((a + c) / 2 * r), y = (c - a) * r;
  return Math.hypot(x, y) * R;
};

const airports = await csv('airports');   // id, ident, type, name, lat, lon, …
const runways = await csv('runways');
const byAirport = new Map();
for (const r of runways) {
  const [, ref, , lenFt, widthFt, surface, , closed, , leLat, leLon, , , , , heLat, heLon] = r;
  if (closed === '1' || !PAVED.test(surface) || !leLat || !heLat) continue;
  const p = [+leLat, +leLon, +heLat, +heLon];
  const len = dist(p[0], p[1], p[2], p[3]);
  if (len < 1200 || !Number.isFinite(len)) continue;
  if (!byAirport.has(ref)) byAirport.set(ref, []);
  byAirport.get(ref).push({ p, len, width: Math.round((+widthFt || 148) * 0.3048), lenFt: +lenFt });
}

const out = {};
for (const theater of ['europe', 'gulf']) {
  const src = readFileSync(`src/world/theaters/${theater}.ts`, 'utf8');
  for (const m of src.matchAll(/\['(\w+)', '([^']+)', '(blue|red)', ([\d.-]+), ([\d.-]+), [\d.]+, \d+\]/g)) {
    const [, id, name, , lat, lon] = m;
    let best = null, bd = 4000;
    for (const a of airports) {
      const la = +a[4], lo = +a[5];
      if (Math.abs(la - lat) > 0.1 || Math.abs(lo - lon) > 0.15 || !byAirport.has(a[0])) continue;
      const d = dist(+lat, +lon, la, lo);
      if (d < bd) { bd = d; best = a; }
    }
    if (!best) { console.log(`${theater} ${id}: no match`); continue; }
    const rw = byAirport.get(best[0]).sort((a, b) => b.len - a.len);
    out[id] = rw.map((r) => [...r.p.map((v) => +v.toFixed(5)), r.width]);
    console.log(`${theater} ${id} → ${best[1]} ${best[3]}: ${rw.map((r) => Math.round(r.len) + ' m').join(', ')}`);
  }
}

const body = Object.entries(out).map(([id, rws]) => `  ${id}: [${rws.map((r) => `[${r.join(', ')}]`).join(', ')}],`).join('\n');
writeFileSync('src/world/theaters/runways.ts', `// Generated by scripts/terrain/bake-runways.mjs from OurAirports (public domain) — do not edit by hand.
// Per airbase id: its open paved runways, longest first, as [threshold lat, lon, other threshold lat, lon, width m].
export const RUNWAYS: Record<string, Array<[number, number, number, number, number]>> = {
${body}
};
`);
